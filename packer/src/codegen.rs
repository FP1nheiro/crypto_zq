//! Emit the embedded build material (RFC §15 step 6, §17 step 4). This is baked
//! into the client binary *before* hardening so VMProtect/OLLVM cover the share
//! constants (RFC §17 gotcha).
//!
//! Two forms are emitted:
//!   * `material.bin` / `pubkey.bin` — raw blobs for the standalone example and CI
//!     codegen-into-resource flows;
//!   * `czq_build_material.h` — C header with the 4 shares as *separate* arrays
//!     (meant to live in distinct translation units / `.rodata` regions, RFC §7.3)
//!     plus an assembler that hands crypto-core the 177-byte material buffer.

use std::fs;
use std::path::Path;

use anyhow::Result;

pub const MATERIAL_LEN: usize = 1 + 32 + 16 + 4 * 32 + 32; // 209 (FORMAT.md §1.1)

pub fn material_bytes(
    build_seed: &[u8; 32],
    build_salt: &[u8; 16],
    shares: &[[u8; 32]; 4],
    sprite_secret: &[u8; 32],
) -> Vec<u8> {
    let mut v = Vec::with_capacity(MATERIAL_LEN);
    v.push(1); // format_version
    v.extend_from_slice(build_seed);
    v.extend_from_slice(build_salt);
    for s in shares {
        v.extend_from_slice(s);
    }
    v.extend_from_slice(sprite_secret); // independent SPRITE key root (key Y)
    v
}

fn c_array(name: &str, bytes: &[u8]) -> String {
    let mut s = format!(
        "static const unsigned char {name}[{}] = {{\n    ",
        bytes.len()
    );
    for (i, b) in bytes.iter().enumerate() {
        s.push_str(&format!("0x{b:02X},"));
        if (i + 1) % 12 == 0 {
            s.push_str("\n    ");
        }
    }
    s.push_str("\n};\n");
    s
}

/// Emit `embed/lj_czq_perm.h` — the inverse opcode table + version flag that a
/// *patched client LuaJIT* includes (Lua ladder Phase 1). `lj_bcread.c` uses it to
/// un-permute opcodes while reading a VM-marked dump. Derived from the same
/// `build_seed` as the packer's forward permutation, so the two agree by
/// construction; rotates every build.
pub fn write_lua_perm_header(out_dir: &Path, build_seed: &[u8; 32]) -> Result<()> {
    let embed = out_dir.join("embed");
    fs::create_dir_all(&embed)?;

    let inv = czq_core::luajit::invert(&czq_core::luajit::opcode_perm(build_seed));

    let mut h = String::new();
    h.push_str("// GENERATED by czq-pack — do not edit. Per-build LuaJIT opcode map\n");
    h.push_str("// (Lua ladder Phase 1). #include this from a patched lj_bcread.c and map\n");
    h.push_str("// each opcode byte of a VM-marked dump through lj_czq_inv[] while reading.\n");
    h.push_str("#ifndef LJ_CZQ_PERM_H\n#define LJ_CZQ_PERM_H\n\n");
    // The high bit set on the dump version byte marks a permuted dump.
    h.push_str(&format!("#define LJ_CZQ_VER_FLAG 0x{:02X}\n\n", czq_core::luajit::VM_VERSION_FLAG));
    h.push_str(&c_array("lj_czq_inv", &inv));
    h.push_str("\n#endif /* LJ_CZQ_PERM_H */\n");

    fs::write(embed.join("lj_czq_perm.h"), h)?;
    Ok(())
}

#[allow(clippy::too_many_arguments)]
pub fn write_all(
    out_dir: &Path,
    build_seed: &[u8; 32],
    build_salt: &[u8; 16],
    shares: &[[u8; 32]; 4],
    sprite_secret: &[u8; 32],
    pubkey: &[u8; 32],
) -> Result<()> {
    let embed = out_dir.join("embed");
    fs::create_dir_all(&embed)?;

    let material = material_bytes(build_seed, build_salt, shares, sprite_secret);
    fs::write(embed.join("material.bin"), &material)?;
    fs::write(embed.join("pubkey.bin"), pubkey)?;

    let mut h = String::new();
    h.push_str("// GENERATED by czq-pack — do not edit. Embed BEFORE hardening (RFC §17).\n");
    h.push_str("// The 4 shares are separate arrays on purpose: place them in distinct\n");
    h.push_str("// translation units / .rodata regions so a single grep can't lift the key.\n");
    h.push_str("#pragma once\n#include <string.h>\n\n");
    h.push_str(&c_array("czq_build_seed", build_seed));
    h.push_str(&c_array("czq_build_salt", build_salt));
    h.push_str(&c_array("czq_share0", &shares[0]));
    h.push_str(&c_array("czq_share1", &shares[1]));
    h.push_str(&c_array("czq_share2", &shares[2]));
    h.push_str(&c_array("czq_share3", &shares[3]));
    h.push_str(&c_array("czq_sprite_secret", sprite_secret));
    h.push_str(&c_array("czq_ed25519_pubkey", pubkey));
    h.push_str(&format!(
        "\n#define CZQ_MATERIAL_LEN {MATERIAL_LEN}\n\n\
// Assemble the 177-byte material buffer crypto-core expects. In production keep\n\
// this inside the VMProtect/OLLVM-virtualized region and secure_zero `out` after\n\
// czq_boot returns.\n\
static inline void czq_assemble_material(unsigned char out[CZQ_MATERIAL_LEN]) {{\n\
    unsigned char* p = out;\n\
    *p++ = 1;\n\
    memcpy(p, czq_build_seed, 32); p += 32;\n\
    memcpy(p, czq_build_salt, 16); p += 16;\n\
    memcpy(p, czq_share0, 32); p += 32;\n\
    memcpy(p, czq_share1, 32); p += 32;\n\
    memcpy(p, czq_share2, 32); p += 32;\n\
    memcpy(p, czq_share3, 32); p += 32;\n\
    memcpy(p, czq_sprite_secret, 32); p += 32;\n\
}}\n"
    ));
    fs::write(embed.join("czq_build_material.h"), h)?;
    Ok(())
}
